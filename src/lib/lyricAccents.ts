export interface LyricAccent {
  svg: string
  term: string
}

export function getLyricAccent(text: string): LyricAccent | undefined {
  const normalized = text.toLocaleLowerCase().replace(/[^a-z0-9\s'-]/g, ' ')
  const accent = lyricAccents
    .map((group) => ({
      group,
      term: group.terms.find((term) =>
        new RegExp(`\\b${term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+')}\\b`, 'i').test(normalized),
      ),
    }))
    .find(({ term }) => term)
  if (!accent?.term) return undefined

  const hash = [...text].reduce((value, char) => value + char.charCodeAt(0), 0)
  return {
    svg: accent.group.svgs[hash % accent.group.svgs.length],
    term: accent.term,
  }
}

export function getLyricAccentWordIndex(words: string[], term: string): number {
  const normalize = (word: string) => word.toLocaleLowerCase().replace(/[^a-z0-9]/g, '')
  const phrase = term.split(/\s+/).map(normalize).filter(Boolean)
  const normalizedWords = words.map(normalize)

  for (let i = 0; i <= normalizedWords.length - phrase.length; i++) {
    if (phrase.every((word, offset) => normalizedWords[i + offset] === word)) return i
  }
  return -1
}
